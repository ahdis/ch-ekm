#!/usr/bin/env bash
#
# SDC template-based $extract for the Mpox testcase.
#
# Pipeline:  sushi .  ->  ./scripts/assemble-mpox.sh  ->  this script
#
# Runs the CSIRO/aehrc reference $extract (@aehrc/sdc-template-extract) on a Mpox
# QuestionnaireResponse using the FSH-authored Bundle template (ChEkmDocumentMpoxTemplate),
# producing a document Bundle conforming to Profile: ChEkmDocumentMpox.
#
# Mpox-specific coverage vs. the Gonorrhoea testcase (scripts/extract-gonorrhoea.sh):
#   * `manifestation` repeats (check-box) -> the template's context on evidence[0] must produce
#     ONE Condition.evidence entry PER answered manifestation, each with a single code.
#   * a manifestationBeginDate (the "unknown" box disabled) -> the asserted onsetDateTime branch (Gonorrhoea covers the
#     data-absent branch).
#   * the person group carries full names (surname/givenname), not initials.
#   * the disease-specific question (issue #43: close contact after the onset of the manifestation,
#     with a remark): answered, and NOT extracted into a resource — its group is copied into a
#     separate QuestionnaireResponse to ChEkmQuestionnaireMpoxDiseaseSpecificAssembled, referenced
#     from section[diagnosis].entry[questionnaire-response]. Optional on the form, so the entry is
#     CONDITIONAL: a second run on a copy of the response without the group checks the closed state.
#
# Inputs (generated by `sushi .`; assembled questionnaire by scripts/assemble-mpox.sh):
#   - Questionnaire:           the assembled ChEkmQuestionnaireMpoxAssembled if present
#                              (what the renderer loads), else the modular root
#   - QuestionnaireResponse:   ChEkmQuestionnaireResponseMpox
#
# Usage:
#   ./scripts/extract-mpox.sh [QUESTIONNAIRE_JSON] [QR_JSON] [OUT_JSON] [TX_OUT_JSON]

set -euo pipefail
cd "$(dirname "$0")/.."

ASSEMBLED="input/resources/Questionnaire-ChEkmQuestionnaireMpoxAssembled.json"
ROOT="fsh-generated/resources/Questionnaire-ChEkmQuestionnaireMpox.json"
DEFAULT_Q="$ROOT"
[ -f "$ASSEMBLED" ] && DEFAULT_Q="$ASSEMBLED"

Q="${1:-$DEFAULT_Q}"
QR="${2:-fsh-generated/resources/QuestionnaireResponse-ChEkmQuestionnaireResponseMpox.json}"
OUT="${3:-input/resources/Bundle-ChEkmDocumentMpox-extracted.json}"
# The whole $extract output — the transaction (ChEkmExtractTransaction) that stores the document
# AND the DocumentReference linking it to the launch patient. $OUT is its document entry alone.
TX_OUT="${4:-input/resources/Bundle-ChEkmTransactionMpox-extracted.json}"

for f in "$Q" "$QR"; do
  [ -f "$f" ] || { echo "ERROR: $f not found. Run 'sushi .' first."; exit 1; }
done

# Install the reference library on first run.
if [ ! -d scripts/extract/node_modules ]; then
  echo "Installing @aehrc/sdc-template-extract ..."
  (cd scripts/extract && npm install --silent)
fi

echo "Questionnaire:         $Q"
echo "QuestionnaireResponse: $QR"
echo

node scripts/extract/extract.cjs "$Q" "$QR" "$OUT" "$TX_OUT"

# The extract engine emits the document Bundle without an `id`. Since $OUT is a predefined IG
# resource (input/resources/), the IG Publisher needs a stable logical id — add one derived from
# the output filename (Bundle-<id>.json -> <id>, e.g. ChEkmDocumentMpox-extracted), placed
# right after resourceType.
if command -v jq >/dev/null 2>&1; then
  BUNDLE_ID="$(basename "$OUT" .json)"; BUNDLE_ID="${BUNDLE_ID#Bundle-}"
  tmp="$(mktemp)"
  jq --arg id "$BUNDLE_ID" '{resourceType, id: $id} + del(.id)' "$OUT" > "$tmp" && mv "$tmp" "$OUT"
fi

echo
echo "Extracted document Bundle: $OUT"
command -v jq >/dev/null 2>&1 && jq -r '
  "  type: \(.type)",
  "  entries:",
  (.entry[] | "    - \(.resource.resourceType) \(.fullUrl)")
' "$OUT" || true

# Mpox regression check: one evidence entry per answered manifestation, one code each.
if command -v jq >/dev/null 2>&1; then
  echo
  echo "Condition.evidence (expect one entry per answered manifestation):"
  jq -r '
    [.entry[].resource | select(.resourceType == "Condition")][0].evidence
    | to_entries[]
    | "    evidence[\(.key)].code[0].coding[0] = \(.value.code[0].coding[0].code) (\(.value.code[0].coding[0].display))"
  ' "$OUT" || true

  echo
  echo "Disease-specific QuestionnaireResponse in the document (expect it to name the disease-specific"
  echo "questionnaire and hold ONLY the close-contact group, issue #43):"
  jq -r '([.entry[].resource | select(.resourceType == "QuestionnaireResponse")][0]
         | "    questionnaire = \(.questionnaire // "(absent)")",
           "    items         = \(.item[0].linkId) > \(.item[0].item | map(.linkId) | join(", "))")
         // "    (no QuestionnaireResponse emitted)"' "$OUT" || true
  # The group is copied by one context-gated `$this` templateExtractValue, so it must be
  # byte-identical to the same linkId's item in the form's response, and nothing else may appear.
  jq -e --slurpfile src "$QR" '
    [.entry[].resource | select(.resourceType == "QuestionnaireResponse")][0].item[0].item as $copied
    | ($copied | map(.linkId)) as $ids
    | ([$src[0] | .. | objects | select(.linkId? as $l | $ids | index($l))]) as $orig
    | ($copied | length) > 0 and ($copied == $orig)
  ' "$OUT" >/dev/null \
    && echo "    every copied item is byte-identical to the form response's item: OK" \
    || echo "    WARNING: the copied items DIFFER from the form response (or a placeholder survived)"

  # CLOSED state: the same QR without the close-contact group must extract to a document WITHOUT the
  # QuestionnaireResponse entry and without the section[diagnosis] reference to it. Temporary files
  # only; the IG examples are the open state above.
  echo
  echo "Disease-specific question UNANSWERED (expect no QuestionnaireResponse and no reference to it):"
  CLOSED_DIR="$(mktemp -d)"
  jq 'walk(if type == "object" and has("item")
           then .item |= map(select(.linkId != "close-contact-after-onset"))
           else . end)' "$QR" > "$CLOSED_DIR/qr.json"
  node scripts/extract/extract.cjs "$Q" "$CLOSED_DIR/qr.json" "$CLOSED_DIR/out.json" >/dev/null
  jq -r '"    QuestionnaireResponse entries: \([.entry[].resource | select(.resourceType == "QuestionnaireResponse")] | length)",
         "    section[diagnosis] entries:    \([.entry[].resource | select(.resourceType == "Composition")][0].section[]
                                             | select(.code.coding[0].code == "29308-4") | .entry | map(.reference) | join(", "))"' \
    "$CLOSED_DIR/out.json" || true
  jq -e '([.entry[].resource | select(.resourceType == "QuestionnaireResponse")] | length) == 0
         and ([.. | objects | .reference? // empty | select(startswith("QuestionnaireResponse/"))] | length) == 0' \
    "$CLOSED_DIR/out.json" >/dev/null \
    && echo "    closed state: OK" \
    || echo "    WARNING: a QuestionnaireResponse (or a reference to one) was emitted although nothing was answered"
  # The other entries must not move when the gated QuestionnaireResponse entry is dropped: the closed
  # document is the open one minus that entry and its reference.
  jq -e --slurpfile open "$OUT" '
    def strip: del(.identifier, .timestamp) | .entry |= map(select(.resource.resourceType != "QuestionnaireResponse"))
      | (.entry[] | select(.resource.resourceType == "Composition") | .resource.section[0].entry) |= map(select(.reference | startswith("QuestionnaireResponse/") | not));
    (. | strip | del(.id)) == ($open[0] | strip | del(.id))
  ' "$CLOSED_DIR/out.json" >/dev/null \
    && echo "    every other entry unchanged: OK" \
    || echo "    WARNING: dropping the QuestionnaireResponse changed other entries"

  # Remark alone (contact unanswered) still opens the gate: the group has an answered child.
  echo
  echo "Only the remark answered (expect the QuestionnaireResponse, holding just the remark):"
  jq 'walk(if type == "object" and has("item")
           then .item |= map(select(.linkId != "close-contact"))
           else . end)' "$QR" > "$CLOSED_DIR/qr-note.json"
  node scripts/extract/extract.cjs "$Q" "$CLOSED_DIR/qr-note.json" "$CLOSED_DIR/out-note.json" >/dev/null
  jq -r '([.entry[].resource | select(.resourceType == "QuestionnaireResponse")][0]
         | "    items = \(.item[0].item[0].linkId) > \(.item[0].item[0].item | map(.linkId) | join(", "))")
         // "    WARNING: no QuestionnaireResponse emitted"' "$CLOSED_DIR/out-note.json" || true
  rm -rf "$CLOSED_DIR"
fi
